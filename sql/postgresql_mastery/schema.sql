-- PostgreSQL 15+ | Training schema only | Synthetic data
CREATE SCHEMA IF NOT EXISTS hda;
SET search_path TO hda, public;

CREATE TABLE IF NOT EXISTS departments (
  department_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department_name text NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS drugs (
  drug_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  drug_name text NOT NULL,
  therapeutic_class text,
  route text,
  CONSTRAINT uq_drug_name_route UNIQUE (drug_name, route)
);
CREATE TABLE IF NOT EXISTS encounters (
  encounter_id text PRIMARY KEY,
  patient_id text NOT NULL,
  admission_date date NOT NULL,
  discharge_date date NOT NULL,
  age_years smallint CHECK (age_years BETWEEN 0 AND 120),
  department_id integer NOT NULL REFERENCES departments(department_id),
  payer_type text,
  length_of_stay_days numeric(8,2) NOT NULL CHECK (length_of_stay_days >= 0),
  discharge_disposition text,
  readmission_30d_flag boolean,
  CHECK (discharge_date >= admission_date)
);
CREATE TABLE IF NOT EXISTS medication_orders (
  order_id text PRIMARY KEY,
  encounter_id text NOT NULL REFERENCES encounters(encounter_id),
  drug_id integer NOT NULL REFERENCES drugs(drug_id),
  order_date date NOT NULL,
  order_status text NOT NULL,
  quantity numeric(12,2) NOT NULL CHECK (quantity > 0),
  unit_cost_inr numeric(12,2) CHECK (unit_cost_inr >= 0),
  prescriber_id text,
  pharmacy_location text,
  CHECK (order_date >= DATE '2000-01-01')
);
CREATE INDEX IF NOT EXISTS ix_encounters_department_admission ON encounters(department_id, admission_date);
CREATE INDEX IF NOT EXISTS ix_orders_encounter_date ON medication_orders(encounter_id, order_date);
CREATE INDEX IF NOT EXISTS ix_orders_drug_status ON medication_orders(drug_id, order_status);
