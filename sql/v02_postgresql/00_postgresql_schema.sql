-- PostgreSQL schema for the Healthcare Data Analyst Academy practice dataset
-- Run in a new, empty practice database. Do not run against production systems.
CREATE SCHEMA IF NOT EXISTS academy;
SET search_path TO academy;

CREATE TABLE departments (
 department_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 department_code VARCHAR(12) NOT NULL UNIQUE,
 department_name VARCHAR(100) NOT NULL
);
CREATE TABLE patients (
 patient_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 synthetic_patient_code VARCHAR(20) NOT NULL UNIQUE,
 sex VARCHAR(12) CHECK (sex IN ('F','M','Other','Unknown')),
 date_of_birth DATE,
 district VARCHAR(80),
 created_at DATE NOT NULL
);
CREATE TABLE encounters (
 encounter_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 patient_id INTEGER NOT NULL REFERENCES patients(patient_id),
 department_id INTEGER NOT NULL REFERENCES departments(department_id),
 admission_date DATE NOT NULL,
 discharge_date DATE,
 encounter_type VARCHAR(20) NOT NULL CHECK (encounter_type IN ('OPD','IPD','Emergency')),
 systolic_bp NUMERIC(6,1),
 diastolic_bp NUMERIC(6,1),
 length_of_stay_days INTEGER CHECK (length_of_stay_days >= 0),
 outcome VARCHAR(20) CHECK (outcome IN ('Discharged','Transferred','Died','Ongoing')),
 readmitted_30d SMALLINT CHECK (readmitted_30d IN (0,1) OR readmitted_30d IS NULL)
);
CREATE TABLE diagnoses (
 diagnosis_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 encounter_id INTEGER NOT NULL REFERENCES encounters(encounter_id),
 diagnosis_code VARCHAR(12) NOT NULL,
 diagnosis_label VARCHAR(120) NOT NULL,
 diagnosis_role VARCHAR(20) NOT NULL CHECK (diagnosis_role IN ('Primary','Secondary'))
);
CREATE TABLE prescriptions (
 prescription_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 encounter_id INTEGER NOT NULL REFERENCES encounters(encounter_id),
 generic_name VARCHAR(120) NOT NULL,
 drug_class VARCHAR(80) NOT NULL,
 dose VARCHAR(40),
 route VARCHAR(30),
 start_date DATE NOT NULL,
 stop_date DATE
);
CREATE TABLE laboratory_results (
 result_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 encounter_id INTEGER NOT NULL REFERENCES encounters(encounter_id),
 test_code VARCHAR(20) NOT NULL,
 test_name VARCHAR(120) NOT NULL,
 result_value NUMERIC(12,3),
 unit VARCHAR(30) NOT NULL,
 result_date DATE NOT NULL,
 abnormal_flag SMALLINT CHECK (abnormal_flag IN (0,1) OR abnormal_flag IS NULL)
);
CREATE INDEX idx_encounters_patient_date ON encounters(patient_id, admission_date);
CREATE INDEX idx_encounters_department_date ON encounters(department_id, admission_date);
CREATE INDEX idx_diagnoses_encounter ON diagnoses(encounter_id);
CREATE INDEX idx_prescriptions_encounter ON prescriptions(encounter_id);
CREATE INDEX idx_labs_encounter_test_date ON laboratory_results(encounter_id, test_code, result_date);
